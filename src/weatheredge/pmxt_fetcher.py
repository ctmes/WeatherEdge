def _is_weather_slug(text: str) -> bool:
    """Check if text contains any weather-related slug keywords."""
    text_lower = text.lower()
    # Reject non-weather topics first
    for block in NON_WEATHER_BLOCKLIST:
        if block in text_lower:
            return False
    # Check for weather keywords
    return any(kw in text_lower for kw in PMXT_WEATHER_SLUGS)


# ---------------------------------------------------------------------------
# ID mapping (Gamma 32-byte CID -> PMXT 20-byte truncated MID)
# ---------------------------------------------------------------------------


def _normalize_id(val: str | int) -> str:
    """
    Normalize any ID (conditionId or clobTokenId, hex or decimal)
    to the 66-character hex format used in PMXT (0x + 64 lowercase hex).

    Gamma sometimes returns token IDs as JSON-escaped strings with
    surrounding quotes still present (e.g. '"123456"' instead of '123456').
    We strip those before parsing.
    """
    if not val:
        return ""

    try:
        if isinstance(val, str):
            # Strip surrounding whitespace and any embedded quote characters
            # that survive JSON double-parsing (e.g. '"123456"' → '123456')
            val = val.strip().strip('"').strip("'")
            if val.lower().startswith("0x"):
                ival = int(val, 16)
            else:
                ival = int(val)
        else:
            ival = int(val)
        # Convert to 64-char hex with 0x prefix
        return f"0x{ival:064x}".lower()
    except (ValueError, TypeError):
        # Fallback for non-numeric strings (should be rare after stripping)
        s = str(val).lower().strip('"').strip("'")
        if not s.startswith("0x"):
            s = "0x" + s
        return s


# ---------------------------------------------------------------------------
# Fetch order book snapshots for specific market IDs
# ---------------------------------------------------------------------------


def _extract_snapshots_from_df(
    df: pl.DataFrame,
    id_map: dict[str, str],
    target_ts: datetime,
) -> dict[str, dict]:
    """
    Filter a raw PMXT DataFrame for book_snapshot rows matching id_map keys
    that occurred at or before target_ts, then return the latest per market.

    Handles the Polars type mismatch: timestamp_received is Datetime(ms, UTC)
    so we must compare against a proper pl.datetime literal, not a raw int.
    """
    normalized_ids = list(id_map.keys())

    # --- timestamp filter -------------------------------------------------
    # timestamp_received dtype: Datetime(time_unit='ms', time_zone='UTC')
    # Comparing against a raw Python int silently produces wrong results in
    # Polars because it treats the int as microseconds/ticks, not epoch-ms.
    # Cast the column to Int64 (epoch-ms) first so the comparison is correct.
    ts_col = pl.col("timestamp_received").cast(pl.Int64)
    target_ms = int(target_ts.timestamp() * 1000)

    filtered = df.filter(
        pl.col("market_id").is_in(normalized_ids)
        & (pl.col("update_type") == "book_snapshot")
        & (ts_col <= target_ms)
    )

    log.info(
        "Snapshot filter: %d IDs, target_ms=%d → %d rows matched",
        len(normalized_ids), target_ms, len(filtered),
    )

    if filtered.is_empty():
        # Check if IDs exist but all snapshots are AFTER the target timestamp.
        # This happens when target_ms is before the PMXT archive started for
        # that day (e.g. decision at 06:51 UTC but archive starts at 12:53 UTC).
        # In that case, use the EARLIEST available snapshot as the best proxy —
        # it's still a real pre-resolution market price.
        id_only = df.filter(
            pl.col("market_id").is_in(normalized_ids)
            & (pl.col("update_type") == "book_snapshot")
        )
        if not id_only.is_empty():
            earliest_ms = id_only.select(ts_col.alias("ts")).get_column("ts").min()
            lag_minutes = (earliest_ms - target_ms) / 60_000
            log.warning(
                "target_ms=%d is %.0f min BEFORE the earliest snapshot (epoch-ms=%d). "
                "PMXT archive didn't exist yet at decision time. "
                "Using earliest available snapshot as price proxy.",
                target_ms, lag_minutes, earliest_ms,
            )
            # Use earliest snapshot per market instead (sort ascending)
            filtered = id_only.sort(ts_col, descending=False)
        else:
            log.warning(
                "No book_snapshot rows found for any of the %d market IDs. "
                "Sample normalized IDs: %s",
                len(normalized_ids), normalized_ids[:3],
            )
            return {}

    # Take the latest snapshot per market (sort descending, first-seen wins)
    filtered = filtered.sort(ts_col, descending=True)

    result: dict[str, dict] = {}
    seen: set[str] = set()
    for row in filtered.iter_rows(named=True):
        tmid = row["market_id"]
        mid = id_map.get(tmid, tmid)
        if mid in seen:
            continue
        seen.add(mid)
        try:
            data = json.loads(row["data"]) if isinstance(row["data"], str) else row["data"]
            result[mid] = data
        except (json.JSONDecodeError, TypeError):
            continue

    return result


def _extract_price_from_local_ticks(
    slug: str,
    target_ts: datetime,
) -> dict[str, Any] | None:
    """
    Search local weather_tick_data for the closest trade to target_ts.
    Returns a mock orderbook dict {best_bid, best_ask, side}.
    """
    path = LOCAL_TICK_DATA_DIR / f"{slug}.parquet"
    if not path.exists():
        return None

    try:
        # Load only necessary columns to keep it fast
        df = pl.read_parquet(path, columns=["timestamp_us", "price", "outcome"])
        # timestamp_us is microseconds since epoch
        target_us = int(target_ts.timestamp() * 1_000_000)

        # Find trades at or before target_ts
        # outcome="Yes" is already filtered in get_data.py but let's be safe
        subset = df.filter(
            (pl.col("timestamp_us") <= target_us) &
            (pl.col("outcome") == "Yes")
        ).sort("timestamp_us", descending=True)

        if subset.is_empty():
            # Try taking the EARLIEST trade if target is before first trade
            subset = df.filter(pl.col("outcome") == "Yes").sort("timestamp_us", descending=False)
            if subset.is_empty():
                return None
            row = subset.row(0, named=True)
            log.debug("Local tick: using earliest trade for %s (target was before start)", slug)
        else:
            row = subset.row(0, named=True)

        price = float(row["price"])
        # Mock a narrow spread around the last traded price
        return {
            "best_bid": price - 0.005,
            "best_ask": price + 0.005,
            "side": "YES",
            "timestamp": row["timestamp_us"] / 1_000, # ms for consistency
            "source": "local_ticks"
        }
    except Exception as e:
        log.warning("Failed to read local tick data for %s: %s", slug, e)
        return None


def fetch_orderbook_at_timestamp(
    target_ts: datetime,
    market_ids: set[str],
    slug_map: dict[str, str] | None = None,
) -> dict[str, dict]:
    """
    Download the pmxt hourly file(s) matching target_ts and extract the latest
    book_snapshot for each market_id that occurred at or before target_ts.

    If slug_map is provided, checks LOCAL_TICK_DATA_DIR first for high-fidelity
    trade data.
    """
    result: dict[str, dict] = {}
    remaining_ids = set(market_ids)

    # Step 1: Try local tick data first if slugs are known
    if slug_map:
        for mid, slug in slug_map.items():
            if mid in market_ids:
                local_ob = _extract_price_from_local_ticks(slug, target_ts)
                if local_ob:
                    result[mid] = local_ob
                    remaining_ids.remove(mid)

    if not remaining_ids:
        log.info("Resolved all %d markets from local tick data", len(market_ids))
        return result

    if result:
        log.info("Resolved %d markets from local ticks, fetching %d from PMXT archive",
                 len(result), len(remaining_ids))

    date_str = target_ts.date().isoformat()
    hour = target_ts.hour

    # Cache key now includes the full remaining_ids set so changing the set
    # (e.g. adding condition_ids) busts any stale cached empty results.
    ids_hash = hashlib.sha256(",".join(sorted(remaining_ids)).encode()).hexdigest()[:12]
    cache_k = _cache_key("orderbook_v3", date_str, str(hour), ids_hash)

    cached = _read_cache(cache_k)
    if cached is not None:
        # A cached DataFrame with 0 rows means a previously confirmed empty
        # result — return {} without re-downloading.
        if cached.is_empty():
            return result
        for row in cached.iter_rows(named=True):
            result[row["market_id"]] = json.loads(row["data"])
        log.debug("Cache hit: %d additional orderbooks for %s hour=%02d", len(result) - len(market_ids) + len(remaining_ids), date_str, hour)
        return result

    id_map = {_normalize_id(mid): mid for mid in remaining_ids}

    # Bail out immediately for future dates — PMXT only archives past data.
    today = datetime.utcnow().date()
    if target_ts.date() > today:
        log.debug("Skipping PMXT fetch for future date %s (today=%s)", date_str, today)
        return {}

    # Try target hour first, then scan forward to find the first file with data.
    # PMXT archive typically starts mid-day (~12:00 UTC); early-hour targets
    # (e.g. 06:51 from ECMWF 00Z run) won't have data in hours 5-6.
    # We scan from max(hour, 10) forward so we skip known-empty early files.
    start_hour = max(hour, 10)
    hours_to_try = list(range(start_hour, 24))
    if hour < start_hour:
        # Original target was before our start — prepend it so it's tried first
        # (in case PMXT does have data for that specific hour on some days)
        hours_to_try = [hour] + hours_to_try

    pmxt_result: dict[str, dict] = {}
    got_404_on_reliable_hour = False
    for h in hours_to_try:
        if got_404_on_reliable_hour:
            break
        url = f"{PMXT_ARCHIVE_BASE}/polymarket_orderbook_{date_str}T{h:02d}.parquet"
        log.info("Fetching pmxt orderbook: %s (hour=%02d)", date_str, h)
        try:
            df = _download_parquet(url, columns=["market_id", "update_type", "timestamp_received", "data"])
        except httpx.HTTPStatusError as e:
            if e.response.status_code == 404 and h >= 12:
                # A 404 on a mid-day-or-later hour means no archive for this
                # date at all — no point trying subsequent hours.
                log.warning(
                    "404 on hour=%02d for %s — no PMXT data for this date, stopping scan.",
                    h, date_str,
                )
                got_404_on_reliable_hour = True
            else:
                log.warning("Failed to fetch %s: %s", url, e)
            continue
        except Exception as e:
            log.warning("Failed to fetch %s: %s", url, e)
            continue

        if df.is_empty():
            del df
            continue

        ob = _extract_snapshots_from_df(df, id_map, target_ts)
        # Free the large parquet frame immediately — these files are hundreds of
        # MB of all-Polymarket orderbook data; holding even one in RAM while
        # looping over dates causes OOM on the VPS.
        del df
        gc.collect()

        if ob:
            pmxt_result.update(ob)
            log.info(
                "Found %d/%d additional orderbooks in hour=%02d file for %s",
                len(ob), len(remaining_ids), h, date_str,
            )
            break
        else:
            log.debug("Hour=%02d had no matching snapshots, trying next hour", h)

    result.update(pmxt_result)

    # Cache the pmxt portion only (local tick data is sourced separately each time)
    cache_rows = [{"market_id": mid, "data": json.dumps(d)} for mid, d in pmxt_result.items()]
    cache_df = pl.DataFrame(
        cache_rows if cache_rows else {"market_id": pl.Series([], dtype=pl.Utf8),
                                       "data":      pl.Series([], dtype=pl.Utf8)}
    )
    _write_cache(cache_k, cache_df)

    if not result:
        log.warning(
            "No orderbook data found for %s (target=%s, tried hours %s). "
            "Markets will fall back to Gamma post-resolution prices → 1%% floor.",
            date_str, target_ts.isoformat(), hours_to_try,
        )

    return result


def fetch_orderbook_for_markets(
    target_date: date,
    market_ids: set[str],
) -> dict[str, dict]:
    """
    Download a pmxt hourly file and extract the latest book_snapshot for
    each market_id in the given set.

    Returns {market_id: {best_bid, best_ask, bids, asks, timestamp}}.
    """
    cache_k = _cache_key("orderbook", target_date.isoformat(),
                         hashlib.sha256(",".join(sorted(market_ids)).encode()).hexdigest()[:8])
    cached = _read_cache(cache_k)
    if cached is not None:
        log.debug("Cache hit for orderbook on %s", target_date)
        # Convert cached DataFrame back to dict
        result: dict[str, dict] = {}
        for row in cached.iter_rows(named=True):
            result[row["market_id"]] = json.loads(row["data"])
        return result

    url = build_date_urls(target_date, target_date)[0][1]
    log.info("Fetching pmxt orderbook for %s ...", target_date)

    _PMXT_COLS = ["market_id", "update_type", "timestamp_received", "data"]
    try:
        df = _download_parquet(url, columns=_PMXT_COLS)
    except Exception as e:
        log.warning("Failed to fetch %s: %s (retrying once...)", url, e)
        time.sleep(2)
        try:
            df = _download_parquet(url, columns=_PMXT_COLS)
        except Exception as e2:
            log.warning("Retry failed for %s: %s — skipping", url, e2)
            return {}

    if df.is_empty():
        return {}

    # PMXT Parquet market_id is a 32-byte hex ID.
    id_map = {_normalize_id(mid): mid for mid in market_ids}
    normalized_ids = list(id_map.keys())

    # Filter for our market IDs and book_snapshot events
    filtered = df.filter(
        pl.col("market_id").is_in(normalized_ids)
        & (pl.col("update_type") == "book_snapshot")
    )

    if filtered.is_empty():
        log.debug("No matching book_snapshots for %d market IDs on %s",
                  len(market_ids), target_date)
        return {}

    # Take the latest snapshot per market
    filtered = filtered.sort("timestamp_received", descending=True)

    result: dict[str, dict] = {}
    seen: set[str] = set()

    for row in filtered.iter_rows(named=True):
        tmid = row["market_id"]
        # Map back to the original full ID
        mid = id_map.get(tmid, tmid)
        if mid in seen:
            continue
        seen.add(mid)
        try:
            data = json.loads(row["data"]) if isinstance(row["data"], str) else row["data"]
            result[mid] = data
        except (json.JSONDecodeError, TypeError):
            continue

    log.info("Found book snapshots for %d / %d weather markets on %s",
             len(result), len(market_ids), target_date)

    # Cache the filtered result
    if result:
        cache_rows = [{"market_id": mid, "data": json.dumps(d)} for mid, d in result.items()]
        cache_df = pl.DataFrame(cache_rows)
        _write_cache(cache_k, cache_df)

    return result


def enrich_market_with_orderbook(
    parsed: ParsedMarket,
    orderbook: dict | None = None,
    per_bin_orderbooks: dict[int, dict] | None = None,
) -> ParsedMarket:
    """
    Replace post-resolution prices on a ParsedMarket with real historical
    bid/ask midpoint from the pmxt order book snapshot.

    For binary markets (2 outcomes): uses a single orderbook dict.
    For multi-outcome (daily events): uses per_bin_orderbooks mapping
    bin_index -> orderbook dict to set each bin's YES midpoint price.
    """
    if per_bin_orderbooks and len(parsed.outcome_prices) > 2:
        # Multi-outcome: set each bin's price from its own order book
        original_prices = len(parsed.outcome_prices)
        new_prices = [0.0] * original_prices
        enriched_count = 0
        for bin_idx, ob in per_bin_orderbooks.items():
            if bin_idx >= original_prices:
                continue
            best_bid = float(ob.get("best_bid") or 0)
            best_ask = float(ob.get("best_ask") or 0)

            if best_bid > 0 and best_ask > 0:
                midpoint = (best_bid + best_ask) / 2.0
            elif best_bid > 0:
                midpoint = best_bid
            elif best_ask > 0:
                midpoint = best_ask
            else:
                continue  # No useful price data for this bin

            # The midpoint from the YES side of the child market
            side = ob.get("side", "YES")
            if side == "YES":
                new_prices[bin_idx] = midpoint
            else:
                new_prices[bin_idx] = 1.0 - midpoint
            enriched_count += 1

        parsed.outcome_prices = new_prices
        if enriched_count > 0:
            log.info(
                "Multi-outcome enrichment: set %d/%d bin prices from order book",
                enriched_count, len(parsed.outcome_prices),
            )
        else:
            log.warning("No orderbook data found for multi-outcome event. Using Gamma prices as fallback.")
        return parsed

    if orderbook is None:
        log.debug("No orderbook provided for binary market enrichment. Keeping existing prices.")
        return parsed

    best_bid = float(orderbook.get("best_bid") or 0)
    best_ask = float(orderbook.get("best_ask") or 0)

    if best_bid > 0 and best_ask > 0:
        midpoint = (best_bid + best_ask) / 2.0
    elif best_bid > 0:
        midpoint = best_bid
    elif best_ask > 0:
        midpoint = best_ask
    else:
        return parsed  # No useful price data

    # For binary markets, replace outcome_prices with [midpoint, 1-midpoint]
    side = orderbook.get("side", "YES")
    if side == "YES":
        yes_price = midpoint
    else:
        yes_price = 1.0 - midpoint

    if len(parsed.outcome_prices) == 2:
        parsed.outcome_prices = [yes_price, 1.0 - yes_price]
    # Multi-outcome with only a single orderbook entry — not enough data,
    # skip rather than inject partial prices

    return parsed


# ---------------------------------------------------------------------------
# Top-level fetcher (matches fetch_resolved_markets signature)
# ---------------------------------------------------------------------------


async def fetch_pmxt_resolved_markets(
    start: date,
    end: date,
    *,
    model_name: str = "ecmwf_ifs",
    latency_seconds: int = 60,
) -> list[tuple[ParsedMarket, dict]]:
    """
    Fetch weather markets from Gamma, then enrich with real historical
    prices from the pmxt archive order book snapshots.
    """
    import asyncio
    from weatheredge.backtest_fetchers import (
        fetch_resolved_markets,
        fetch_resolved_daily_events,
    )
    from weatheredge.config import MODEL_RELEASE_CHART
    from tqdm.asyncio import tqdm

    # Warn if date range predates known archive availability
    PMXT_ARCHIVE_START = date(2026, 2, 22)  # confirmed earliest data
    if start < PMXT_ARCHIVE_START:
        log.warning(
            "pmxt archive may not have data before %s (requested %s). "
            "Order book enrichment may be incomplete — falling back to Gamma prices.",
            PMXT_ARCHIVE_START, start,
        )

    # Step 1: get resolved weather markets from Gamma (for metadata + resolution)
    legacy_pairs = await fetch_resolved_markets(start, end)
    daily_pairs = await fetch_resolved_daily_events(start, end)
    all_pairs = legacy_pairs + daily_pairs

    log.info("Gamma returned %d resolved weather markets for pmxt enrichment", len(all_pairs))

    if not all_pairs:
        return []

    # Step 2: collect all market IDs we need order book data for.
    #
    # PMXT indexes order books by Polymarket conditionId (hex, 66 chars).
    #
    # For BINARY markets: parsed.condition_id is the hex conditionId -> add it.
    #
    # For MULTI-OUTCOME daily events: parsed.condition_id is the INTEGER Gamma
    # event ID (e.g. "218765") which is never in PMXT.  The actual tradeable
    # conditionIds live on each child market inside raw["markets"][i]["conditionId"].
    # We must extract and add those instead.
    market_id_set: set[str] = set()
    for idx, (parsed, raw) in enumerate(all_pairs):
        child_markets = raw.get("markets", [])
        if child_markets:
            # Multi-outcome: add each child market's conditionId
            for child in child_markets:
                cid = child.get("conditionId") or child.get("condition_id") or ""
                if cid:
                    market_id_set.add(str(cid))
        else:
            # Binary: parsed.condition_id is the real hex conditionId
            cid = parsed.condition_id
            if cid:
                market_id_set.add(cid)
        # Also add token IDs for forward-compat (currently don't match PMXT)
        for tid in parsed.token_ids:
            market_id_set.add(tid)

    log.info(
        "Step 2: collected %d unique market IDs for PMXT lookup "
        "(%d pairs, child conditionIds + binary conditionIds + token IDs)",
        len(market_id_set), len(all_pairs),
    )

    # Step 3: for each day in the range, fetch order book snapshots
    loop = asyncio.get_event_loop()
    all_orderbooks: dict[str, dict] = {}

    # Build slug map for local tick lookups
    slug_map: dict[str, str] = {}
    for parsed, raw in all_pairs:
        slug = raw.get("slug")
        if slug and parsed.condition_id:
            slug_map[parsed.condition_id] = slug
        # Also map child markets for multi-outcome
        for child in raw.get("markets", []):
            c_slug = child.get("slug")
            c_cid = child.get("conditionId") or child.get("condition_id")
            if c_slug and c_cid:
                slug_map[str(c_cid)] = c_slug

    unique_dates = sorted(list(set(
        p.resolution_date for p, _ in all_pairs if p.resolution_date
    )))
    
    log.info("Fetching pmxt archive order books for %d unique dates (latency=%ds)...", 
             len(unique_dates), latency_seconds)
    
    for d in tqdm(unique_dates, desc="pmxt Archive", unit="day", ncols=80):
        # Calculate precise decision timestamp based on model release
        # Default to 00Z run
        release_info = MODEL_RELEASE_CHART.get(model_name, {}).get("00")
        if release_info:
            h, m = release_info
            # We assume decision is made on the SAME day as resolution for daily weather,
            # using the 00Z model run that arrives shortly after.
            target_ts = datetime.combine(d, datetime.min.time()) + timedelta(
                hours=h, minutes=m, seconds=latency_seconds
            )
        else:
            # Fallback: midday on resolution date
            target_ts = datetime.combine(d, datetime.min.time()) + timedelta(hours=12)

        ob = await loop.run_in_executor(
            None, fetch_orderbook_at_timestamp, target_ts, market_id_set, slug_map,
        )
        # Keep the latest snapshot we find for each market
        for mid, data in ob.items():
            all_orderbooks[mid] = data

    log.info("Collected order book data for %d / %d market IDs from pmxt archive",
             len(all_orderbooks), len(market_id_set))

    # Step 4: enrich ParsedMarket prices with real bid/ask
    enriched_pairs: list[tuple[ParsedMarket, dict]] = []
    enriched_count = 0

    for idx, (parsed, raw) in enumerate(all_pairs):
        if "markets" in raw and len(raw["markets"]) > 0:
            # Multi-outcome: look up each bin by the CHILD market's conditionId.
            # parsed.condition_id is the INTEGER Gamma event ID (e.g. "218765")
            # which is never in PMXT. The child hex conditionIds are the real keys.
            sorted_markets = sorted(
                raw["markets"], key=lambda m: int(m.get("groupItemThreshold", "0"))
            )
            per_bin_obs: dict[int, dict] = {}
            pmxt_obs: dict[str, dict] = {}

            for bin_idx, child in enumerate(sorted_markets):
                child_cid = str(child.get("conditionId") or child.get("condition_id") or "")
                ob = all_orderbooks.get(child_cid) if child_cid else None
                # Fallback to token ID if child conditionId didn't match
                if not ob and bin_idx < len(parsed.token_ids):
                    ob = all_orderbooks.get(parsed.token_ids[bin_idx])
                if ob:
                    per_bin_obs[bin_idx] = ob
                    pmxt_obs[child_cid] = ob

            if per_bin_obs:
                parsed = enrich_market_with_orderbook(
                    parsed, per_bin_orderbooks=per_bin_obs
                )
                enriched_count += 1
                raw["_pmxt_orderbook"] = pmxt_obs
                log.debug(
                    "Multi-outcome %s: enriched %d/%d bins via child conditionIds",
                    parsed.question, len(per_bin_obs), len(sorted_markets),
                )
            else:
                log.warning(
                    "No orderbook found for multi-outcome event condition_id=%s (%s). "
                    "Child conditionIds tried: %s. "
                    "Prices will be 0.0 -> floored to 1%% by normalisation.",
                    parsed.condition_id, parsed.question,
                    [str(m.get("conditionId", "?"))[:16] for m in sorted_markets[:3]],
                )
        else:
            # Binary market: conditionId is the PMXT primary key (confirmed by probe).
            # Try it first, then fall back to token IDs for forward-compat.
            ob = all_orderbooks.get(parsed.condition_id)

            if not ob:
                for tid in parsed.token_ids:
                    if tid in all_orderbooks:
                        ob = all_orderbooks[tid]
                        log.debug("Binary market matched via token_id %s (not condition_id)", tid)
                        break

            if ob:
                parsed = enrich_market_with_orderbook(parsed, orderbook=ob)
                enriched_count += 1
                raw["_pmxt_orderbook"] = ob
            else:
                log.warning(
                    "No orderbook found for market condition_id=%s (%s). "
                    "Prices will be 0.0 → floored to 1%% by normalisation. "
                    "Check that this conditionId appears in the PMXT file for this date.",
                    parsed.condition_id, parsed.question,
                )

        enriched_pairs.append((parsed, raw))

    log.info("Enriched %d markets with pmxt historical prices (%d unchanged)",
             enriched_count, len(all_pairs) - enriched_count)

    return enriched_pairs